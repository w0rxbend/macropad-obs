"""Writes firmware/core/font_noto<size>.c: 4 bpp alpha glyphs of Noto Sans Regular (spec 9 fw-ui).

Release 1 is Latin (spec R1): ASCII, Latin-1 and the ellipsis the renderer ends a cut text with.
The output is committed, so `just test` needs neither Pillow nor the face. Run it again only to
change the face, the sizes or the glyph set:

    cad/.venv/bin/python tools/gen_font.py /usr/share/fonts/noto/NotoSans-Regular.ttf

The glyph data is a derivative of the face and stays under its licence, SIL OFL 1.1
(firmware/core/font_OFL.txt).
"""

import hashlib
import sys
from pathlib import Path

from PIL import ImageFont

SIZES = (14, 20, 28)
CODEPOINTS = [*range(0x20, 0x7F), *range(0xA0, 0x100), 0x2026]
EXPECTED_FAMILY = ("Noto Sans", "Regular")
OUT_DIR = Path(__file__).resolve().parent.parent / "firmware" / "core"


def alpha4(level):
    """An 8-bit coverage level as 0..15, rounded."""
    return (level * 15 + 127) // 255


def glyph_rows(font, char):
    """The glyph's box and its 4 bpp rows, two pixels a byte, high nibble first."""
    mask, (x_off, y_off) = font.getmask2(char, mode="L")
    width, height = mask.size
    packed = bytearray()
    for y in range(height):
        row = [alpha4(mask.getpixel((x, y))) for x in range(width)]
        row += [0] * (width % 2)
        packed += bytes(row[i] << 4 | row[i + 1] for i in range(0, len(row), 2))
    return width, height, x_off, y_off, bytes(packed)


def c_bytes(blob):
    lines = []
    for start in range(0, len(blob), 16):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in blob[start : start + 16]) + ",")
    return "\n".join(lines)


def render_size(face_path, digest, size):
    font = ImageFont.truetype(str(face_path), size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    entries = []
    for codepoint in CODEPOINTS:
        char = chr(codepoint)
        width, height, x_off, y_off, packed = glyph_rows(font, char)
        advance = int(font.getlength(char) + 0.5)
        for name, value, low, high in (("advance", advance, 0, 255), ("width", width, 0, 255),
                                       ("height", height, 0, 255), ("x", x_off, -128, 127),
                                       ("y", y_off, -128, 127)):
            if not low <= value <= high:
                sys.exit(f"U+{codepoint:04X} at {size} px: {name} {value} does not fit the glyph table")
        entries.append(f"\t{{0x{codepoint:04x}, {advance}, {width}, {height}, {x_off}, {y_off}, {len(bitmap)}}},")
        bitmap += packed
    name = f"FONT_NOTO{size}"
    return f"""// SPDX-License-Identifier: OFL-1.1
// Generated by tools/gen_font.py. Do not edit. Noto Sans Regular, sha256 {digest},
// {size} px, 4 bpp. Copyright 2022 The Noto Project Authors; SIL OFL 1.1, see font_OFL.txt.
#include "font.h"

static const uint8_t BITMAP[] = {{
{c_bytes(bitmap)}
}};

static const font_glyph_t GLYPHS[] = {{
{chr(10).join(entries)}
}};

const font_t {name} = {{{ascent + descent}, {ascent}, {len(entries)}, GLYPHS, BITMAP}};
"""


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_font.py NotoSans-Regular.ttf")
    face_path = Path(sys.argv[1])
    family = ImageFont.truetype(str(face_path), SIZES[0]).getname()
    if family != EXPECTED_FAMILY:
        sys.exit(f"{face_path}: is {family}, want {EXPECTED_FAMILY}")
    digest = hashlib.sha256(face_path.read_bytes()).hexdigest()
    for size in SIZES:
        out = OUT_DIR / f"font_noto{size}.c"
        out.write_text(render_size(face_path, digest, size))
        print(f"{out}: {out.stat().st_size} bytes")


if __name__ == "__main__":
    main()
